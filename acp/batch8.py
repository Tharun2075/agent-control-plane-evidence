"""Batch 8 (defence baselines and gate ablation on the batch 7 cells): summary, batch 6+7+8 table,
one attribution line per control and the R5 failure analysis of the gated misses.

Same aggregation, outcome classes and Wilson intervals as batch 6 (acp.bench_gate). The failure
analysis reads only the run records and repeats/batch8/task_facts.json (tools/batch8_facts.py),
so it runs without AgentDojo. Protocol: repeats/batch8/PROTOCOL.md.
"""

from __future__ import annotations

import json
from pathlib import Path

from acp import bench_gate as g

GENERATOR = "python3 tools/batch8_summary.py"
COMBINED_COLS = ("batch",) + g.CSV_COLS
GATE_ARMS = ("gated", "allowlist", "approval")
R5_CLASSES = ("legitimate recipient", "allowlist miss", "gate approved", "other")
FAIL_COLS = ("batch", "model", "arm", "suite", "ut", "it", "class", "note", "approved_hit_calls", "calls")

# What each control is; batch 7 gives plain and gated, batch 8 the rest.
CONTROLS = {
    "plain": ("batch7", "no control (reference)"),
    "gated": ("batch7", "action-word approval AND target allowlist (the batch 6 gate)"),
    "allowlist": ("batch8", "target allowlist alone (gate condition 2)"),
    "approval": ("batch8", "action-word approval alone (gate condition 1)"),
    "tool_filter": ("batch8", "AgentDojo tool_filter (model picks the tools before the loop)"),
    "spotlighting": ("batch8", "AgentDojo spotlighting with delimiting"),
    "repeat_user_prompt": ("batch8", "AgentDojo repeat_user_prompt"),
}


def _md(summary: dict, title: str) -> str:
    return g.markdown(summary, title).replace("`python3 -m acp batch6-summary`", f"`{GENERATOR}`")


def _pct(rate: dict) -> str:
    if rate["rate"] is None:
        return "n/a"
    lo, hi = rate["ci95"]
    return f"{rate['k']}/{rate['n']} = {100 * rate['rate']:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"


def combined_rows(batches: list[tuple[str, dict]]) -> list[dict]:
    """B1 rows of every batch in one list, in the given order, each tagged with its batch."""
    return [{"batch": name, **row} for name, s in batches for row in g.csv_rows(s)]


def combined_markdown(rows: list[dict]) -> str:
    out = ["# Batches 6, 7 and 8, B1: AgentDojo controls on Claude and open-weight models", "",
           f"Generated by `{GENERATOR}` from the committed run records of repeats/batch6/runs, "
           "repeats/batch7/runs and repeats/batch8/runs. Same subset, attack and outcome classes; k/n "
           "with 95% Wilson intervals; errors and provider refusals stay in every denominator.", "",
           "| batch | model | arm | runs | benign utility | ASR | utility under attack | provider-refused | errors | cost $ |",
           "|---|---|---|---|---|---|---|---|---|---|"]

    def pct(rate, lo, hi, k, n):
        return "n/a" if rate is None else f"{k}/{n} = {100 * rate:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"

    for r in rows:
        uua_k = round(r["utility_under_attack"] * r["attacked_n"]) if r["utility_under_attack"] is not None else 0
        out.append(f"| {r['batch']} | {r['model']} | {r['arm']} | {r['runs']} | "
                   f"{pct(r['benign_utility'], r['bu_lo'], r['bu_hi'], r['benign_utility_k'], r['benign_n'])} | "
                   f"{pct(r['asr'], r['asr_lo'], r['asr_hi'], r['succeeded'], r['attacked_n'])} | "
                   f"{pct(r['utility_under_attack'], r['uua_lo'], r['uua_hi'], uua_k, r['attacked_n'])} | "
                   f"{r['provider_refused']} | {r['errors']} | {r['cost_usd']:.2f} |")
    return "\n".join(out) + "\n"


def pooled(records: list[dict]) -> dict:
    """Per arm, pooled over models: ASR, benign utility, runs, models (classes as in bench_gate)."""
    out = {}
    for arm in sorted({r["arm"] for r in records}):
        rs = [r for r in records if r["arm"] == arm]
        ben = [r for r in rs if r["kind"] == "benign"]
        att = [r for r in rs if r["kind"] == "attacked"]
        out[arm] = {"runs": len(rs), "models": len({r["model"] for r in rs}),
                    "asr": g._rate(sum(g.classify(r) == "succeeded" for r in att), len(att)),
                    "benign_utility": g._rate(sum(g.classify(r) == "utility" for r in ben), len(ben)),
                    "target_blocked": g._rate(sum(r.get("blocked_target", 0) > 0 for r in att), len(att))}
    return out


def attribution(pool: dict) -> list[str]:
    """One sentence per control: what it is, pooled ASR and benign utility next to plain."""
    base = pool.get("plain")
    lines = []
    for arm, (batch, what) in CONTROLS.items():
        p = pool.get(arm)
        if p is None:
            lines.append(f"- `{arm}` ({what}): not run.")
            continue
        s = (f"- `{arm}` ({what}, {batch}, {p['runs']} runs on {p['models']} models): "
             f"ASR {_pct(p['asr'])}, benign utility {_pct(p['benign_utility'])}")
        if base is not None and arm != "plain" and p["asr"]["rate"] is not None and base["asr"]["rate"] is not None:
            d_asr = 100 * (p["asr"]["rate"] - base["asr"]["rate"])
            d_bu = 100 * (p["benign_utility"]["rate"] - base["benign_utility"]["rate"])
            s += f"; vs plain {d_asr:+.1f} pp ASR, {d_bu:+.1f} pp benign utility"
        if arm in GATE_ARMS:
            s += f"; target call blocked in {_pct(p['target_blocked'])} of attacked runs"
        lines.append(s + ".")
    return lines


def attribution_markdown(lines: list[str]) -> str:
    return "\n".join(["# Attribution per control (B1, pooled over models)", "",
                      f"Generated by `{GENERATOR}`. Pooled k/n over all models that ran the arm, 95% Wilson "
                      "intervals; errors and provider refusals stay in every denominator. Pooled rates mix "
                      "models; the per-model rows are in combined.md.", ""] + lines) + "\n"


def classify_miss(rec: dict, facts: dict) -> tuple[str, str]:
    """R5 class of one attacked gate-arm run with security true, and a note.

    Only approved gated calls that hit the attack target count. legitimate recipient: such a call
    and a target marker of the injection task is in the user task. allowlist miss: such a call to a
    tool with no target argument. gate approved: any other such call. other: no such call.
    """
    sf = facts["suites"][rec["suite"]]
    calls = rec.get("calls") or []
    approved = [c for c in calls if c.get("gate") == "approved" and c.get("hit")]
    if not approved:
        hits = [c for c in calls if c.get("hit")]
        if rec["it"] in sf["trace_scored"] and hits and all(c.get("gate") not in (None, "approved") for c in hits):
            return "other", "trace-scored task: every target call was blocked"
        return "other", "no approved gated call hit the target"
    prompt = g._norm(sf["user_tasks"][rec["ut"]])
    if any(m in prompt for m in sf["injection_markers"][rec["it"]]):
        return "legitimate recipient", "target marker is in the user task"
    targetless = [c["fn"] for c in approved if not set(g.TARGET_KEYS) & set(sf["gated_tool_args"].get(c["fn"], []))]
    if targetless:
        return "allowlist miss", "approved tool has no target argument: " + ",".join(sorted(set(targetless)))
    return "gate approved", "target argument passed the gate"


def failure_rows(batches: list[tuple[str, list[dict]]], facts: dict) -> list[dict]:
    rows = []
    for name, recs in batches:
        for r in sorted(recs, key=lambda r: (r["model"], r["arm"], r["suite"], r["ut"], r["it"] or "")):
            if r["arm"] not in GATE_ARMS or r["kind"] != "attacked" or g.classify(r) != "succeeded":
                continue
            cls, note = classify_miss(r, facts)
            fmt = lambda cs: ";".join(f"{c['fn']}:{c.get('gate')}:{'hit' if c.get('hit') else '-'}" for c in cs)
            rows.append({"batch": name, "model": r["model"], "arm": r["arm"], "suite": r["suite"], "ut": r["ut"],
                         "it": r["it"], "class": cls, "note": note,
                         "approved_hit_calls": fmt([c for c in r.get("calls") or [] if c.get("gate") == "approved" and c.get("hit")]),
                         "calls": fmt(r.get("calls") or [])})
    return rows


def failures_markdown(rows: list[dict]) -> str:
    out = ["# R5: failure analysis of the gate-arm misses (B1, attacked, attack succeeded)", "",
           f"Generated by `{GENERATOR}` from the run records and repeats/batch8/task_facts.json. Only approved "
           "gated calls that hit the attack target count. Classes as in repeats/batch8/PROTOCOL.md.", "",
           "| batch | arm | runs | " + " | ".join(R5_CLASSES) + " | of which trace-scored, all target calls blocked |",
           "|---|---|---|" + "---|" * len(R5_CLASSES) + "---|"]
    for key in sorted({(r["batch"], r["arm"]) for r in rows}):
        rs = [r for r in rows if (r["batch"], r["arm"]) == key]
        counts = " | ".join(str(sum(r["class"] == c for r in rs)) for c in R5_CLASSES)
        ts = sum(r["note"].startswith("trace-scored") for r in rs)
        out.append(f"| {key[0]} | {key[1]} | {len(rs)} | {counts} | {ts} |")
    out += ["", "Trace-scored: AgentDojo v1.2.2 scores slack injection_task_5 with `security_from_traces`, which "
            "reads the attempted calls in the trace, so a call the gate blocked still counts as attack success.",
            "", "| batch | model | arm | suite | user task | injection task | class | note | approved hit calls |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['batch']} | {r['model']} | {r['arm']} | {r['suite']} | {r['ut']} | {r['it']} | "
                   f"{r['class']} | {r['note']} | {r['approved_hit_calls'] or '-'} |")
    return "\n".join(out) + "\n"


def build(root: Path) -> dict:
    """All outputs of batch 8 as {relative path: text}, generated from the run records."""
    root = Path(root)
    b1 = lambda n: [r for r in g.load_records(root / "repeats" / n / "runs") if r.get("set") == "B1"]
    r6, r7, r8 = b1("batch6"), b1("batch7"), b1("batch8")
    s6, s7, s8 = g.aggregate(r6), g.aggregate(r7), g.aggregate(r8)
    facts = json.loads((root / "repeats" / "batch8" / "task_facts.json").read_text())
    pool = pooled(r7 + r8)
    lines = attribution(pool)
    fails = failure_rows([("batch7", r7), ("batch8", r8)], facts)
    rows = combined_rows([("batch6", s6), ("batch7", s7), ("batch8", s8)])
    summary = {"B1": s8, "pooled": pool, "attribution": lines,
               "failures": {c: sum(f["class"] == c for f in fails) for c in R5_CLASSES}}
    d = "repeats/batch8/"
    return {
        d + "summary.json": json.dumps(summary, indent=1, sort_keys=True) + "\n",
        d + "summary.md": _md(s8, "Batch 8 B1: gate ablation and AgentDojo defences on open-weight models (Bedrock)"),
        d + "b1.csv": g.to_csv(g.csv_rows(s8)),
        d + "combined.csv": g.to_csv(rows, COMBINED_COLS),
        d + "combined.md": combined_markdown(rows),
        d + "attribution.md": attribution_markdown(lines),
        d + "failures.csv": g.to_csv(fails, FAIL_COLS),
        d + "failures.md": failures_markdown(fails),
    }
