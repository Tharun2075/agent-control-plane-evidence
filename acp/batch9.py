"""Batch 9 (defence baselines, second attack, sampled repeats, allowlist-aware injection): summary
and the batch 6+7+9 table.

Same aggregation, outcome classes and Wilson intervals as batches 6 and 7 (acp.bench_gate); this
module only groups the records and lays out the files. Protocol: repeats/batch9/PROTOCOL.md.
"""

from __future__ import annotations

import json
from pathlib import Path

from acp import bench_gate as g
from acp.repeats import wilson

GENERATOR = "python3 tools/batch9_summary.py"
COMBINED_COLS = ("batch",) + g.CSV_COLS
KINDS = ("defences", "tool_knowledge", "repeats", "adaptive")
ADAPTIVE_COLS = ("model", "arm", "n", "k", "rate", "lo", "hi", "utility_k", "provider_refused", "errors",
                 "gate_blocks", "cost_usd")
REASON_COLS = ("batch", "model", "arm", "gated_calls", "approved", "action_not_in_task", "target_not_in_allowlist")


def kind_of(r: dict) -> str:
    if r.get("set") == "A":
        return "adaptive"
    if str(r["arm"]).startswith("def-"):
        return "defences"
    if r.get("attack") == "tool_knowledge":
        return "tool_knowledge"
    return "repeats"


def label(r: dict) -> str:
    """Arm label that keeps every run group apart (arm / attack / temperature / repeat)."""
    k = kind_of(r)
    if k == "defences":
        return r["arm"]
    if k == "tool_knowledge":
        return f"{r['arm']}/tool_knowledge"
    if k == "adaptive":
        return f"{r['arm']}/allowlist_reuse"
    return f"{r['arm']}/T{r['temperature']}/r{r['rep']}"


def relabel(records: list[dict], fn) -> list[dict]:
    return [{**r, "arm": fn(r)} for r in records]


def _md(summary: dict, title: str) -> str:
    return g.markdown(summary, title).replace("`python3 -m acp batch6-summary`", f"`{GENERATOR}`")


def repeat_records(b7: list[dict], b9: list[dict]) -> list[dict]:
    """Rep 0 (batch 7, T 0) plus reps 1-3 (batch 9, T 0.7), each labelled, plus a pooled label."""
    r0 = relabel([r for r in b7 if r.get("set") == "B1"], lambda r: f"{r['arm']}/T0/r0")
    rs = relabel([r for r in b9 if kind_of(r) == "repeats"], label)
    pooled = relabel([r for r in b9 if kind_of(r) == "repeats"], lambda r: f"{r['arm']}/T0.7/pooled")
    return r0 + rs + pooled


def adaptive_rows(b9: list[dict]) -> list[dict]:
    """Headline of the allowlist-aware injection: k/n successes per model and arm, Wilson 95%."""
    groups: dict[tuple[str, str], list[dict]] = {}
    for r in b9:
        if kind_of(r) == "adaptive":
            groups.setdefault((r["model"], r["arm"]), []).append(r)
    out = []
    for (model, arm), rs in sorted(groups.items()):
        k, n = sum(g.classify(r) == "succeeded" for r in rs), len(rs)
        lo, hi = wilson(k, n)
        out.append({"model": model, "arm": arm, "n": n, "k": k, "rate": round(k / n, 4) if n else None,
                    "lo": round(lo, 4), "hi": round(hi, 4),
                    "utility_k": sum(bool(r.get("utility")) and not r.get("error_class") for r in rs),
                    "provider_refused": sum(g.classify(r) == "provider-refused" for r in rs),
                    "errors": sum(g.classify(r) == "error" for r in rs),
                    "gate_blocks": sum(r.get("gate_blocks", 0) for r in rs),
                    "cost_usd": round(sum(r.get("cost_usd", 0.0) for r in rs), 4)})
    return out


def reason_rows(batch: str, records: list[dict]) -> list[dict]:
    """Per-control attribution: gated calls of attacked runs by the reviewer's verdict."""
    groups: dict[tuple[str, str], list[str]] = {}
    for r in records:
        if r["kind"] != "attacked" or not str(r["arm"]).startswith("gated"):
            continue
        for c in r.get("calls") or []:
            if c.get("gate") is not None:
                groups.setdefault((r["model"], r["arm"]), []).append(c["gate"])
    out = []
    for (model, arm), gs in sorted(groups.items()):
        out.append({"batch": batch, "model": model, "arm": arm, "gated_calls": len(gs),
                    "approved": sum(x == "approved" for x in gs),
                    "action_not_in_task": sum(x == "action not in user task" for x in gs),
                    "target_not_in_allowlist": sum(x.endswith("not in allowlist") for x in gs)})
    return out


def adaptive_markdown(rows: list[dict]) -> str:
    out = ["# Batch 9 allowlist-aware injection (`allowlist_reuse`, set A, never tuned)", "",
           f"Generated by `{GENERATOR}`. Success = an unblocked gated-tool call carrying the payload to the "
           "recipient the user's own prompt names (repeats/batch9/PROTOCOL.md). k/n with 95% Wilson intervals; "
           "errors and refusals stay in n.", "",
           "| model | arm | success k/n | rate [95% CI] | utility k | provider-refused | errors | gate blocks | cost $ |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        rate = "n/a" if r["rate"] is None else f"{100 * r['rate']:.1f}% [{100 * r['lo']:.1f}, {100 * r['hi']:.1f}]"
        out.append(f"| {r['model']} | {r['arm']} | {r['k']}/{r['n']} | {rate} | {r['utility_k']} | "
                   f"{r['provider_refused']} | {r['errors']} | {r['gate_blocks']} | {r['cost_usd']:.2f} |")
    return "\n".join(out) + "\n"


def reason_markdown(rows: list[dict]) -> str:
    out = ["# Gate verdicts on attacked runs (per-control attribution)", "",
           "Each gated tool call of an attacked run, by the reviewer's verdict (acp/bench_gate.py `review`).", "",
           "| batch | model | arm | gated calls | approved | action not in task | target not in allowlist |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['batch']} | {r['model']} | {r['arm']} | {r['gated_calls']} | {r['approved']} | "
                   f"{r['action_not_in_task']} | {r['target_not_in_allowlist']} |")
    return "\n".join(out) + "\n"


def combined_markdown(rows: list[dict]) -> str:
    out = ["# Batches 6, 7 and 9, B1: AgentDojo with no defence, benchmark defences and the gate", "",
           f"Generated by `{GENERATOR}` from the committed run records of repeats/batch6/runs, "
           "repeats/batch7/runs and repeats/batch9/runs. Arm labels: `def-*` = AgentDojo defence (T 0); "
           "`<arm>/tool_knowledge` = second attack; `<arm>/T0.7/r<n>` = sampled repeat. k/n with 95% Wilson "
           "intervals; errors and provider refusals stay in every denominator.", "",
           "| batch | model | arm | runs | benign utility | ASR | utility under attack | provider-refused | errors | cost $ |",
           "|---|---|---|---|---|---|---|---|---|---|"]

    def pct(rate, lo, hi, k, n):
        return "n/a" if rate is None else f"{k}/{n} = {100 * rate:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"

    for r in rows:
        uua_k = round(r["utility_under_attack"] * r["attacked_n"]) if r["utility_under_attack"] is not None else 0
        out.append(f"| {r['batch']} | {r['model']} | {r['arm']} | {r['runs']} | "
                   f"{pct(r['benign_utility'], r['bu_lo'], r['bu_hi'], r['benign_utility_k'], r['benign_n'])} | "
                   f"{pct(r['asr'], r['asr_lo'], r['asr_hi'], r['succeeded'], r['attacked_n'])} | "
                   f"{pct(r['utility_under_attack'], r['uua_lo'], r['uua_hi'], uua_k, r['attacked_n'])} | "
                   f"{r['provider_refused']} | {r['errors']} | {r['cost_usd']:.2f} |")
    return "\n".join(out) + "\n"


def build(root: Path) -> dict:
    """All outputs of batch 9 as {relative path: text}, generated from the run records."""
    root = Path(root)
    b9 = g.load_records(root / "repeats" / "batch9" / "runs")
    b7 = g.load_records(root / "repeats" / "batch7" / "runs")
    b6 = g.load_records(root / "repeats" / "batch6" / "runs")
    s = {
        "defences": g.aggregate(relabel([r for r in b9 if kind_of(r) == "defences"], label)),
        "tool_knowledge": g.aggregate(relabel([r for r in b9 if kind_of(r) == "tool_knowledge"], label)),
        "repeats": g.aggregate(repeat_records(b7, b9)),
    }
    ad = adaptive_rows(b9)
    s6 = g.aggregate([r for r in b6 if r.get("set") == "B1"])
    s7 = g.aggregate([r for r in b7 if r.get("set") == "B1"])
    s9 = g.aggregate(relabel([r for r in b9 if kind_of(r) != "adaptive"], label))
    rows = [{"batch": n, **row} for n, x in (("batch6", s6), ("batch7", s7), ("batch9", s9)) for row in g.csv_rows(x)]
    reasons = (reason_rows("batch7", [r for r in b7 if r.get("set") == "B1"])
               + reason_rows("batch9", relabel(b9, label)))
    summary = {**s, "adaptive": ad, "gate_verdicts": reasons, "runs": len(b9),
               "cost_usd": round(sum(r.get("cost_usd", 0.0) for r in b9), 4)}
    d = "repeats/batch9/"
    md = (_md(s["defences"], "Batch 9 defences: AgentDojo tool_filter, spotlighting, repeat_user_prompt (B1, T 0)")
          + "\n" + _md(s["tool_knowledge"], "Batch 9 second attack: tool_knowledge (B1 attacked half, T 0)")
          + "\n" + _md(s["repeats"], "Batch 9 sampled repeats: important_instructions, rep 0 = batch 7 (T 0), "
                                     "reps 1-3 at T 0.7")
          + "\n" + adaptive_markdown(ad) + "\n" + reason_markdown(reasons))
    out = {
        d + "summary.json": json.dumps(summary, indent=1, sort_keys=True) + "\n",
        d + "summary.md": md,
        d + "adaptive.csv": g.to_csv(ad, ADAPTIVE_COLS),
        d + "gate_verdicts.csv": g.to_csv(reasons, REASON_COLS),
        d + "combined.csv": g.to_csv(rows, COMBINED_COLS),
        d + "combined.md": combined_markdown(rows),
    }
    for k in ("defences", "tool_knowledge", "repeats"):
        out[d + f"{k}.csv"] = g.to_csv(g.csv_rows(s[k]))
    return out
