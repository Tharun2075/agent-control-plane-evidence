"""Batch 7 (AgentDojo on open-weight models via Amazon Bedrock): summary and batch 6+7 table.

Same aggregation, outcome classes and Wilson intervals as batch 6 (acp.bench_gate); this module
only selects the records and lays out the files. Protocol: repeats/batch7/PROTOCOL.md.
"""

from __future__ import annotations

import json
from pathlib import Path

from acp import bench_gate as g

GENERATOR = "python3 tools/batch7_summary.py"
COMBINED_COLS = ("batch",) + g.CSV_COLS
FILES = ("summary.json", "summary.md", "b1.csv", "b2.csv", "combined.csv", "combined.md")


def _md(summary: dict, title: str) -> str:
    return g.markdown(summary, title).replace("`python3 -m acp batch6-summary`", f"`{GENERATOR}`")


def combined_rows(b6: dict, b7: dict) -> list[dict]:
    """B1 rows of both batches in one list, batch 6 first, each tagged with its batch."""
    return [{"batch": name, **row} for name, s in (("batch6", b6), ("batch7", b7)) for row in g.csv_rows(s)]


def combined_markdown(rows: list[dict]) -> str:
    out = ["# Batches 6 and 7, B1: AgentDojo plain vs gated, Claude and open-weight models", "",
           f"Generated by `{GENERATOR}` from the committed run records of repeats/batch6/runs and "
           "repeats/batch7/runs. Same subset, arms, attack and outcome classes; k/n with 95% Wilson "
           "intervals; errors and provider refusals stay in every denominator.", "",
           "| batch | model | arm | runs | benign utility | ASR | utility under attack | provider-refused | errors | cost $ |",
           "|---|---|---|---|---|---|---|---|---|---|"]

    def pct(rate, lo, hi, k, n):
        return "n/a" if rate is None else f"{k}/{n} = {100 * rate:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"

    for r in rows:
        uua_k = round(r["utility_under_attack"] * r["attacked_n"]) if r["utility_under_attack"] is not None else 0
        out.append(f"| {r['batch']} | {r['model']} | {r['arm']} | {r['runs']} | "
                   f"{pct(r['benign_utility'], r['bu_lo'], r['bu_hi'], r['benign_utility_k'], r['benign_n'])} | "
                   f"{pct(r['asr'], r['asr_lo'], r['asr_hi'], r['succeeded'], r['attacked_n'])} | "
                   f"{pct(r['utility_under_attack'], r['uua_lo'], r['uua_hi'], uua_k, r['attacked_n'])} | "
                   f"{r['provider_refused']} | {r['errors']} | {r['cost_usd']:.2f} |")
    return "\n".join(out) + "\n"


def build(root: Path) -> dict:
    """All outputs of batch 7 as {relative path: text}, generated from the run records."""
    root = Path(root)
    b7 = g.load_records(root / "repeats" / "batch7" / "runs")
    b6 = g.load_records(root / "repeats" / "batch6" / "runs")
    s1 = g.aggregate([r for r in b7 if r.get("set") == "B1"])
    s2 = g.aggregate([r for r in b7 if r.get("b2")])
    s6 = g.aggregate([r for r in b6 if r.get("set") == "B1"])
    probes = []
    pf = root / "repeats" / "batch7" / "probe.jsonl"
    if pf.exists():
        probes = [json.loads(x) for x in pf.read_text().splitlines() if x.strip()]
    summary = {"B1": s1, "B2": s2, "probes": probes}
    rows = combined_rows(s6, s1)
    d = "repeats/batch7/"
    return {
        d + "summary.json": json.dumps(summary, indent=1, sort_keys=True) + "\n",
        d + "summary.md": _md(s1, "Batch 7 B1: AgentDojo on open-weight models (Bedrock), plain vs gated")
        + "\n" + _md(s2, "Batch 7 B2: refusal taxonomy, one injection set (arm plain)"),
        d + "b1.csv": g.to_csv(g.csv_rows(s1)),
        d + "b2.csv": g.to_csv(g.csv_rows(s2)),
        d + "combined.csv": g.to_csv(rows, COMBINED_COLS),
        d + "combined.md": combined_markdown(rows),
    }
