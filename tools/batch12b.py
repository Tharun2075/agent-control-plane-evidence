"""Run, summarise or check batch 12b (repeats/batch12b/PROTOCOL.md).

  python3 tools/batch12b.py run      # E1 + E2p at the registered code, then the summary
  python3 tools/batch12b.py summary  # rebuild summary.{json,md} from the records
  python3 tools/batch12b.py --check  # records match the registered code and protocol commit time

Model-free: the scripted attacker only. Before = the committed batch-12 records (code paper-fix12, eaef917).
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from acp import attacker, batch5  # noqa: E402
from acp.repeats import wilson  # noqa: E402

OUT = ROOT / "repeats" / "batch12b"
BEFORE = ROOT / "repeats" / "batch12"
REG = OUT / "code-sha256.json"


def _rows(p: Path) -> list[dict]:
    return batch5._read_rows(p)


def _by_class(rows: list[dict]) -> dict:
    out = {}
    for r in rows:
        if r["bypass"]:
            out[r["class"]] = out.get(r["class"], 0) + 1
    return dict(sorted(out.items()))


def summary() -> dict:
    b1, a1 = _rows(BEFORE / "e1-after" / "attempts.jsonl"), _rows(OUT / "e1-after" / "attempts.jsonl")
    b2, a2 = batch5._e2p(BEFORE), batch5._e2p(OUT)
    k = sum(bool(r["bypass"]) for r in a1)
    res = {"protocol": ["repeats/batch12b/PROTOCOL.md"],
           "e1": {"before": {"attempts": len(b1), "bypass": sum(bool(r["bypass"]) for r in b1), "by_class": _by_class(b1)},
                  "after": {"attempts": len(a1), "bypass": k, "by_class": _by_class(a1),
                            "families": attacker.summarise(a1)["families"], "wilson95_all": wilson(k, len(a1))}},
           "e2p": {"before": {a: v["bypass"] for a, v in b2["arms"].items()},
                   "after": a2}}
    classes = sorted(set(res["e1"]["before"]["by_class"]) | set(res["e1"]["after"]["by_class"]))
    md = ["# Batch 12b summary (generated by tools/batch12b.py; do not edit)", "",
          "E1 scripted attacker, 540 attempts, seed %d. Before = batch 12 E1 records (paper-fix12 code, eaef917); "
          "after = this batch (paper-fix12b code)." % attacker.SEED, "",
          "| class | before | after |", "|---|---|---|"]
    md += [f"| {c} | {res['e1']['before']['by_class'].get(c, 0)} | {res['e1']['after']['by_class'].get(c, 0)} |" for c in classes]
    w = res["e1"]["after"]["wilson95_all"]
    md += [f"| **total** | {res['e1']['before']['bypass']}/{len(b1)} | {k}/{len(a1)} (Wilson 95% {w[0]}-{w[1]}) |", "",
           "E2p paired ablation, 540 attempts per arm, payload hashes equal: %s" % a2.get("payload_hashes_equal"), "",
           "| arm | before bypass | after bypass | b (all-on only) | c (arm only) | Holm p | H5 |", "|---|---|---|---|---|---|---|"]
    for arm in attacker.ablation.ARMS:
        v = a2["vs_all_on"].get(arm, {})
        md.append(f"| {arm} | {res['e2p']['before'].get(arm)} | {a2['arms'][arm]['bypass']} | {v.get('b_all_on_only', '')} | "
                  f"{v.get('c_arm_only', '')} | {'%.3g' % v['p_holm'] if v else ''} | {v.get('h5_holds', '')} |")
    (OUT / "summary.json").write_text(json.dumps(res, indent=2, sort_keys=True) + "\n")
    (OUT / "summary.md").write_text("\n".join(md) + "\n")
    return res


def check() -> list[str]:
    errs = []
    reg = json.loads(REG.read_text())
    t = subprocess.run(["git", "log", "--reverse", "--format=%cI", "--", "repeats/batch12b/PROTOCOL.md"], cwd=ROOT,
                       capture_output=True, text=True).stdout.split()
    if not t:
        return ["PROTOCOL.md not committed"]
    from datetime import datetime
    t0 = datetime.fromisoformat(t[0])
    for m in sorted(OUT.glob("e*/**/meta.json")):
        d = json.loads(m.read_text())
        if d.get("file_sha256") != reg:
            errs.append(f"{m.relative_to(ROOT)}: code hash differs from code-sha256.json")
        if d.get("dirty"):
            errs.append(f"{m.relative_to(ROOT)}: run on a dirty acp tree")
        if datetime.fromisoformat(d["started_utc"].replace("Z", "+00:00")) < t0:
            errs.append(f"{m.relative_to(ROOT)}: started before the protocol commit")
    old = (OUT / "summary.json").read_text() if (OUT / "summary.json").exists() else ""
    if json.dumps(summary(), indent=2, sort_keys=True) + "\n" != old:
        errs.append("summary.json is not what the records give")
    return errs


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "summary"
    if cmd == "register":
        REG.write_text(json.dumps(batch5.code_sha256(), indent=2, sort_keys=True) + "\n")
    elif cmd == "run":
        if batch5.code_sha256() != json.loads(REG.read_text()):
            print("code differs from repeats/batch12b/code-sha256.json; refusing to run")
            return 1
        batch5.run_e1("after", OUT)
        batch5.run_e2p(OUT)
        s = summary()
        print(json.dumps({"e1": {p: s["e1"][p]["bypass"] for p in ("before", "after")},
                          "e2p_after": {a: v["bypass"] for a, v in s["e2p"]["after"]["arms"].items()}}))
    elif cmd == "--check":
        errs = check()
        print("batch12b check:", "ok" if not errs else "FAIL")
        for e in errs:
            print(" ", e)
        return 1 if errs else 0
    else:
        summary()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
