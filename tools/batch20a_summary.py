#!/usr/bin/env python3
"""Summarise batch 20a (A2/A3/A4, Progent arm) from repeats/batch20a/runs/*.jsonl.

Stdlib only, reads logs, makes no model calls. Writes repeats/batch20a/a-summary.md and
a-summary.json. Counting follows batch 19: attack success is security true over all attacked
runs done (an errored run counts as not successful), benign utility is utility true over all
benign runs done. Planned counts come from repeats/batch20a/PROTOCOL.md.

Usage: python3 tools/batch20a_summary.py [--root repeats/batch20a]
"""
import argparse
import collections
import glob
import json
import os

PLANNED = {"a2": 17, "a3": 160, "a4": 77}  # per victim; A4 is gpt-oss-20b only
A4_VICTIM = "openai.gpt-oss-20b-1:0"
# batch 19, gpt-oss-20b, deepseek policy, post-fix (PROTOCOL A1/A4)
BATCH19_A4 = {"asr": [6, 40], "benign_utility": [24, 37], "runs": 77}


def frac(n, d):
    return f"{n}/{d}" if d else "-"


def load(root):
    rows = []
    for path in sorted(glob.glob(os.path.join(root, "runs", "*.jsonl"))):
        with open(path) as fh:
            for line in fh:
                if line.strip():
                    rows.append(json.loads(line))
    return rows


def tally(rs):
    att = [r for r in rs if r.get("kind") == "attacked"]
    ben = [r for r in rs if r.get("kind") == "benign"]
    util = [r for r in rs if isinstance(r.get("utility"), bool)]
    errs = collections.Counter(r["error_class"] for r in rs if r.get("error_class"))
    return {
        "runs": len(rs),
        "attacked": len(att),
        "attack_success": sum(r.get("security") is True for r in att),
        "target_call_attempted": sum(bool(r.get("target_call_attempted")) for r in att),
        "blocked_by_progent": sum((r.get("blocked_target") or 0) > 0 for r in att),
        "runs_with_gate_block": sum((r.get("gate_blocks") or 0) > 0 for r in rs),
        "benign": len(ben),
        "benign_utility": sum(r.get("utility") is True for r in ben),
        "utility_defined": len(util),
        "utility_true": sum(r["utility"] for r in util),
        "errors": sum(errs.values()),
        "error_classes": dict(errs),
        "cost_usd": round(sum(r.get("cost_usd") or 0 for r in rs), 4),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="repeats/batch20a")
    a = ap.parse_args()
    rows = load(a.root)
    groups = collections.defaultdict(list)
    for r in rows:
        groups[(r["b20_set"], r["model"])].append(r)

    out = {"sets": {}, "batch19_a4_reference": BATCH19_A4, "rows_read": len(rows)}
    md = ["# Batch 20a summary (generated by tools/batch20a_summary.py)", "",
          f"Rows read: {len(rows)}. Attack success = security true over attacked runs done;"
          " errored runs count as not successful. 'partial' = runs done < planned.", ""]
    for s in ("a2", "a3", "a4"):
        victims = sorted(m for (ss, m) in groups if ss == s)
        if not victims:
            continue
        md += [f"## {s.upper()}", "",
               "| victim | runs/planned | attack success | target call attempted |"
               " blocked by Progent | utility | errors | spend $ | state |",
               "|---|---|---|---|---|---|---|---|---|"]
        sdict = {}
        allrs = []
        for m in victims:
            rs = groups[(s, m)]
            allrs += rs
            t = tally(rs)
            t["planned"] = PLANNED[s]
            t["state"] = "partial" if t["runs"] < PLANNED[s] else "complete"
            if s == "a3":
                t["per_attack"] = {k: tally([r for r in rs if r.get("attack") == k])
                                   for k in sorted({r.get("attack") for r in rs})}
            sdict[m] = t
            u = (f"benign {frac(t['benign_utility'], t['benign'])}" if t["benign"]
                 else frac(t["utility_true"], t["utility_defined"]))
            md.append(f"| {m} | {t['runs']}/{t['planned']} | {frac(t['attack_success'], t['attacked'])}"
                      f" | {t['target_call_attempted']} | {t['blocked_by_progent']} | {u}"
                      f" | {t['errors']} | {t['cost_usd']:.3f} | {t['state']} |")
        tot = tally(allrs)
        tot["planned"] = PLANNED[s] * len(victims)
        sdict["_total"] = tot
        md.append(f"| **total** | {tot['runs']}/{tot['planned']} | {frac(tot['attack_success'], tot['attacked'])}"
                  f" | {tot['target_call_attempted']} | {tot['blocked_by_progent']}"
                  f" | {frac(tot['utility_true'], tot['utility_defined'])} | {tot['errors']}"
                  f" | {tot['cost_usd']:.3f} | |")
        md.append("")
        if s == "a3":
            md += ["### A3 per attack", "",
                   "| victim | attack | runs | attack success | target call attempted |"
                   " blocked by Progent | utility | errors |", "|---|---|---|---|---|---|---|---|"]
            for m in victims:
                for k, t in sdict[m]["per_attack"].items():
                    md.append(f"| {m} | {k} | {t['runs']} | {frac(t['attack_success'], t['attacked'])}"
                              f" | {t['target_call_attempted']} | {t['blocked_by_progent']}"
                              f" | {frac(t['utility_true'], t['utility_defined'])} | {t['errors']} |")
            md.append("")
        if s == "a4" and A4_VICTIM in sdict:
            t = sdict[A4_VICTIM]
            b = BATCH19_A4
            md += ["### A4 vs batch 19 (gpt-oss-20b, same 77 jobs)", "",
                   "| policy model | runs | attack success | benign utility | errors |",
                   "|---|---|---|---|---|",
                   f"| deepseek.v3.2 (batch 19, post-fix) | {b['runs']} | {frac(*b['asr'])}"
                   f" | {frac(*b['benign_utility'])} | 3 |",
                   f"| mistral-large-3 (batch 20a) | {t['runs']} | {frac(t['attack_success'], t['attacked'])}"
                   f" | {frac(t['benign_utility'], t['benign'])} | {t['errors']} |", ""]
        out["sets"][s] = sdict

    with open(os.path.join(a.root, "a-summary.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(a.root, "a-summary.json"), "w") as fh:
        json.dump(out, fh, indent=1, sort_keys=True)
    print(os.path.join(a.root, "a-summary.md"))


if __name__ == "__main__":
    main()
